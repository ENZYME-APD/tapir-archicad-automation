def system_uses_dark_mode() -> bool:
    """ Whether Windows or macOS is set to dark mode; False elsewhere or when it cannot be read.

    On Windows this is the Windows mode (Settings > Personalization > Colors), which colours the
    taskbar, the Start menu and Alt+Tab, where the icon is shown.
    """
    if sys.platform == "win32":
        try:
            import winreg
            with winreg.OpenKey(winreg.HKEY_CURRENT_USER,
                                r"Software\Microsoft\Windows\CurrentVersion\Themes\Personalize") as key:
                value, _ = winreg.QueryValueEx(key, "SystemUsesLightTheme")
            return value == 0
        except OSError:
            return False
    if sys.platform == "darwin":
        try:
            # Only set, to "Dark", in dark mode.
            result = subprocess.run(["defaults", "read", "-g", "AppleInterfaceStyle"],
                                    capture_output=True, text=True, timeout=5)
        except (OSError, subprocess.SubprocessError):
            return False
        return result.stdout.strip() == "Dark"
    return False


def use_own_taskbar_entry() -> None:
    """ Lets the Windows taskbar show the window's icon instead of Python's.

    Windows groups the windows of a process under the program that started it, here
    python.exe or pythonw.exe, and shows that program's icon in the taskbar. An own
    application id gives the script's window its own entry with its own icon. Call it
    before the first window is created.
    """
    if sys.platform != "win32":
        return
    try:
        import ctypes
        ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID("ENZYME-APD.Tapir.Script")
    except (AttributeError, OSError):
        pass


def apply_tapir_icon(root: tk.Tk, dark: bool | None = None) -> None:
    """ Sets the Tapir icon on root and on every window it opens later, dialogs included.

    dark chooses the dark-mode icon; by default it follows the system's mode.
    """
    if dark is None:
        dark = system_uses_dark_mode()
    pngs = _ICON_PNGS_DARK_MODE_BASE64 if dark else _ICON_PNGS_BASE64
    try:
        # Largest first, as Tk recommends; the window manager picks the size it needs.
        images = [tk.PhotoImage(master=root, data=pngs[size]) for size in sorted(pngs, reverse=True)]
        root.iconphoto(True, *images)
    except tk.TclError:
        return  # a Tk without PNG support (before 8.6) keeps its own icon
    # Tk forgets an image once its Python object is garbage collected.
    root.tapir_icon_images = images
