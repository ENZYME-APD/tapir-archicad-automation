import aclib

# Scripts can keep their own state on elements, invisible in the Archicad UI: string values under
# keys, stored as the user data of the Tapir add-on on the element (project-wide state is kept by
# the project data commands, see project_data_store.py). The data is saved with the project and
# goes away with the element. Setting merges the given keys into what the element already holds,
# so scripts with different keys do not disturb each other. Prefix the keys with the script's
# name. In a Teamwork project the element has to be reserved. The data lives in the element,
# so expect a copy of the element to carry the same pairs: a script that stores an external id
# should treat a repeated id as a copy.

elements = aclib.RunTapirCommand ('GetAllElements')['elements'][:2]

aclib.RunTapirCommand ('SetElementUserData', {
    'elementUserData': [
        {
            'elementId': element['elementId'],
            'userData': [
                { 'key': 'example.database.id', 'value': str (1000 + i) },
                { 'key': 'example.sync.state', 'value': 'new' }
            ]
        } for i, element in enumerate (elements)
    ]
})

aclib.RunTapirCommand ('GetElementUserData', {
    'elements': elements
})

# Another script stores its own key on the first element; the keys of the example are left alone.
aclib.RunTapirCommand ('SetElementUserData', {
    'elementUserData': [
        {
            'elementId': elements[0]['elementId'],
            'userData': [
                { 'key': 'otherscript.marker', 'value': 'generated by otherscript' }
            ]
        }
    ]
})

# Setting a key again replaces its value; keysToDelete removes keys.
aclib.RunTapirCommand ('SetElementUserData', {
    'elementUserData': [
        {
            'elementId': element['elementId'],
            'userData': [
                { 'key': 'example.sync.state', 'value': 'synced' }
            ],
            'keysToDelete': ['example.database.id']
        } for element in elements
    ]
})

# With keys only those pairs are returned.
aclib.RunTapirCommand ('GetElementUserData', {
    'elements': elements,
    'keys': ['example.sync.state', 'otherscript.marker']
})

aclib.RunTapirCommand ('SetElementUserData', {
    'elementUserData': [
        {
            'elementId': element['elementId'],
            'keysToDelete': ['example.sync.state', 'otherscript.marker']
        } for element in elements
    ]
})

aclib.RunTapirCommand ('GetElementUserData', {
    'elements': elements
})
