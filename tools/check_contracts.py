"""Checks the recorded test steps against the schemas of the commands they call, without Archicad.

archicad-addon/Test/checks/*.json are the tests: each step sends params to a command and states what
the response must have (path, eq / len / approx / exists / ...). They only run in Archicad, on a test
project, so a step that sends a parameter the command does not take, or checks a field the command
does not return, is found by whoever runs the project - not by the pull request that wrote it.

This reads the command schemas of docs/archicad-addon (the command reference, generated from the Add-On
sources) and, for every step:
  * validates params against the command's input schema: types, required fields, enums, array items,
    and parameters the schema does not have,
  * resolves every expect path in the command's response schema.

The published reference is regenerated by the weekly release, so it can be up to a week behind the
sources. That is why an unknown parameter or response field is only an error when its name appears
nowhere in the Add-On sources either - a name that does appear there is a field the next release will
publish, and is reported as a note instead. A wrong type, a missing required field or a bad enum value
is an error either way: the step and the schema disagree, and one of them is wrong now.

A step that asserts the command fails is a negative test: it sends what the command must refuse, so
its parameters are out of contract on purpose and are not validated (see ExpectsRefusal).

Usage:
  python tools/check_contracts.py            check every step of every check
  python tools/check_contracts.py -v         also list the steps that passed and the notes: a name the
                                             sources have and the published schemas not yet (docs lag)
  python tools/check_contracts.py --strict   count those notes as errors, for CI, where the schemas are
                                             regenerated from the sources before this runs

Exit code: 1 when a step contradicts a command schema, 0 otherwise.
"""

import argparse
import glob
import json
import os
import re
import sys

REPO_ROOT = os.path.dirname (os.path.dirname (os.path.abspath (__file__)))
DOCS = os.path.join (REPO_ROOT, 'docs', 'archicad-addon')
CHECKS_DIR = os.path.join (REPO_ROOT, 'archicad-addon', 'Test', 'checks')
SOURCES_DIR = os.path.join (REPO_ROOT, 'archicad-addon', 'Sources')

# Test steps may also drive Archicad's own JSON commands, which have no Tapir schema here.
ARCHICAD_PREFIX = 'API.'

# A value the runner fills in from an earlier step's response (see tools/community-test-runner):
# a string that is only '${name}' takes the saved value's own type, so nothing can be said about it.
PLACEHOLDER = re.compile (r'\$\{[A-Za-z_][A-Za-z0-9_]*\}')

# A response key the runner adds itself when Archicad rejects the command.
ENVELOPE_ERROR = '__envelopeError__'

TYPE_CHECKS = {
    'string': lambda value: isinstance (value, str),
    'number': lambda value: isinstance (value, (int, float)) and not isinstance (value, bool),
    'integer': lambda value: (isinstance (value, int) and not isinstance (value, bool))
                             or (isinstance (value, float) and value.is_integer ()),
    'boolean': lambda value: isinstance (value, bool),
    'array': lambda value: isinstance (value, list),
    'object': lambda value: isinstance (value, dict),
    'null': lambda value: value is None,
}


def ReadJsJson (path):
    with open (path, encoding='utf-8-sig') as f:
        text = f.read ()
    return json.loads (re.sub (r'^\s*var\s+\w+\s*=\s*', '', text).rstrip ().rstrip (';'))


def LoadCommands ():
    groups = ReadJsJson (os.path.join (DOCS, 'command_definitions.js'))
    commands = {}
    for group in groups:
        for command in group.get ('commands', []):
            commands[command['name']] = {
                'input': command.get ('inputScheme'),
                'output': command.get ('outputScheme'),
            }
    return commands


def LoadDefinitions ():
    return ReadJsJson (os.path.join (DOCS, 'common_schema_definitions.js'))


def LoadSourceNames ():
    """Every quoted identifier of the Add-On sources: the vocabulary a schema can legitimately use."""
    names = set ()
    for pattern in ('*.cpp', '*.hpp'):
        for path in glob.glob (os.path.join (SOURCES_DIR, pattern)):
            with open (path, encoding='utf-8', errors='replace') as f:
                names.update (re.findall (r'"([A-Za-z_][A-Za-z0-9_]*)"', f.read ()))
    return names


def Resolve (schema, definitions, seen = ()):
    """Follows $ref and merges an allOf, so the caller sees properties and additionalProperties."""
    if not isinstance (schema, dict):
        return {}
    if '$ref' in schema:
        name = schema['$ref'].split ('/')[-1]
        if name in definitions and name not in seen:
            resolved = dict (Resolve (definitions[name], definitions, seen + (name,)))
            resolved.update ({k: v for k, v in schema.items () if k != '$ref'})
            return resolved
        return {}
    if 'allOf' in schema:
        merged = {k: v for k, v in schema.items () if k != 'allOf'}
        properties = {}
        for part in schema['allOf']:
            resolved = Resolve (part, definitions, seen)
            properties.update (resolved.get ('properties', {}))
            for key, value in resolved.items ():
                if key != 'properties':
                    merged.setdefault (key, value)
        if properties:
            merged['properties'] = properties
        return merged
    return schema


def CheckValue (value, schema, definitions, where, errors, notes, sourceNames):
    """Validates a value against a schema; appends findings to errors and notes."""
    if isinstance (value, str) and PLACEHOLDER.fullmatch (value):
        return                          # filled in from an earlier step: type unknown here

    schema = Resolve (schema, definitions)
    if not schema:
        return

    if 'oneOf' in schema or 'anyOf' in schema:
        branches = schema.get ('oneOf') or schema.get ('anyOf')
        closest = None                  # the branch the value came closest to, for the message
        for branch in branches:
            branchErrors, branchNotes = [], []
            CheckValue (value, branch, definitions, where, branchErrors, branchNotes, sourceNames)
            if not branchErrors:
                return
            if closest is None or len (branchErrors) < len (closest):
                closest = branchErrors
        reason = closest[0]
        if reason.startswith (where + ': '):
            reason = reason[len (where) + 2:]
        while 'alternatives (closest: ' in reason:      # a nested oneOf: keep the innermost reason
            reason = reason.split ('alternatives (closest: ', 1)[1]
            if reason.endswith (')'):
                reason = reason[:-1]
        errors.append ('%s: matches none of the %d alternatives (closest: %s)' % (
            where, len (branches), reason))
        return

    if 'enum' in schema and value not in schema['enum']:
        errors.append ('%s: %s is not one of %s' % (where, json.dumps (value), ', '.join (json.dumps (e) for e in schema['enum'])))
        return

    declared = schema.get ('type')
    if declared is not None:
        types = declared if isinstance (declared, list) else [declared]
        if not any (TYPE_CHECKS.get (t, lambda v: True) (value) for t in types):
            errors.append ('%s: %s is %s, the schema says %s' % (
                where, json.dumps (value)[:60], type (value).__name__, '/'.join (types)))
            return

    if isinstance (value, dict):
        properties = schema.get ('properties', {})
        for name in schema.get ('required', []):
            if name not in value:
                errors.append ('%s: %s is required' % (where, name))
        strict = schema.get ('additionalProperties') is False
        for name, item in value.items ():
            if name in properties:
                CheckValue (item, properties[name], definitions, '%s.%s' % (where, name), errors, notes, sourceNames)
            elif strict:
                if name in sourceNames:
                    notes.append ('%s.%s: not in the published schema yet' % (where, name))
                else:
                    errors.append ('%s: %s is not a parameter of the command' % (where, name))
    elif isinstance (value, list) and 'items' in schema:
        for index, item in enumerate (value):
            CheckValue (item, schema['items'], definitions, '%s[%d]' % (where, index), errors, notes, sourceNames)


def ResolvePath (path, schema, definitions, sourceNames):
    """Whether a response path of an expect exists in the schema; returns (ok, note)."""
    if not path or path.startswith (ENVELOPE_ERROR):
        return True, None
    schema = Resolve (schema, definitions)
    tokens = re.findall (r'[^.\[\]]+|\[\d*\*?\]', path)
    for index, token in enumerate (tokens):
        schema = Resolve (schema, definitions)
        if token.startswith ('['):
            items = schema.get ('items')
            if items is None:
                return True, None        # a free-form array: anything inside it can exist
            schema = items
            continue
        if 'properties' in schema:
            if token in schema['properties']:
                schema = schema['properties'][token]
                continue
            if schema.get ('additionalProperties') is False:
                if token in sourceNames:
                    return True, 'lagging'
                return False, None
            return True, None            # properties not described: cannot say it is wrong
        return True, None                # object without properties: free-form
    return True, None


def ExpectsRefusal (step):
    """Whether the step asserts that the command fails - the negative tests send invalid params."""
    if step.get ('allowEnvelopeError'):
        return True
    for rule in step.get ('expect', []) or []:
        path = rule.get ('path', '')
        if path.startswith (ENVELOPE_ERROR) or path == 'error' or path.startswith ('error.'):
            return True
        if '.error' in path or path.endswith ('error'):
            return True                     # a per-item error: the command must refuse that item
        if rule.get ('eq') is False and (path == 'success' or path.endswith ('.success')):
            return True                     # the command must refuse: a per-item success is false
    return False


def CheckStep (path, step, commands, definitions, sourceNames):
    errors, notes = [], []
    command = step.get ('command')
    identifier = '%s: %s' % (os.path.basename (path), step.get ('id') or command)
    if not command or command.startswith (ARCHICAD_PREFIX):
        return errors, notes
    if command not in commands:
        notes.append ('%s: "%s" is not in the published command reference yet' % (identifier, command))
        return errors, notes

    if ExpectsRefusal (step):
        # The step sends what the command must refuse, so its parameters are out of contract on
        # purpose: the refusal is the test.
        return errors, notes

    params = step.get ('params')
    schema = commands[command]['input']
    if params not in (None, {}):
        if schema is None:
            errors.append ('%s: %s takes no parameters, the step sends %s' % (
                identifier, command, ', '.join (sorted (params))))
        else:
            CheckValue (params, schema, definitions, identifier, errors, notes, sourceNames)

    output = commands[command]['output']
    # A rule with exists false asserts the field is absent, so the path is not expected to resolve.
    paths = [(rule.get ('path', ''), 'expect path') for rule in step.get ('expect', []) or []
             if 'expr' not in rule and rule.get ('exists') is not False]
    paths += [(path, 'save path') for path in (step.get ('save') or {}).values ()]
    for path, kind in paths:
        ok, note = ResolvePath (path, output, definitions, sourceNames) if output else (True, None)
        if not ok:
            field = path.split ('.')[-1].split ('[')[0]
            errors.append ('%s: response has no "%s" (%s "%s")' % (identifier, field, kind, path))
        elif note:
            notes.append ('%s: %s "%s" is not in the published schema yet' % (identifier, kind, path))
    return errors, notes


def main ():
    parser = argparse.ArgumentParser (description = __doc__.split ('\n')[0])
    parser.add_argument ('-v', '--verbose', action = 'store_true', help = 'also list the steps that passed')
    parser.add_argument ('--strict', action = 'store_true',
                         help = 'treat a note as an error: for CI, where the schemas are regenerated from '
                                'the sources first, a name they do not have is a disagreement, not docs lag')
    args = parser.parse_args ()

    commands = LoadCommands ()
    definitions = LoadDefinitions ()
    sourceNames = LoadSourceNames ()

    paths = sorted (glob.glob (os.path.join (CHECKS_DIR, '*.json')))
    allErrors = []
    allNotes = []
    steps = 0
    refusals = 0
    for path in paths:
        with open (path, encoding='utf-8-sig') as f:
            check = json.load (f)
        for step in list (check.get ('steps', [])) + (check.get ('teardown') or []):
            steps += 1
            if ExpectsRefusal (step):
                refusals += 1
            errors, notes = CheckStep (path, step, commands, definitions, sourceNames)
            allErrors.extend (errors)
            allNotes.extend (notes)
            if args.verbose and not errors:
                print ('ok   %s: %s' % (os.path.basename (path), step.get ('id') or step.get ('command')))

    if args.strict:
        allErrors.extend (allNotes)
        allNotes = []

    if args.verbose:
        for note in allNotes:
            print ('note: ' + note)
    for error in allErrors:
        print ('error: ' + error, file = sys.stderr)

    print ('%d step(s) in %d check(s) checked against %d command schemas: %d error(s), %d note(s), '
           '%d step(s) refused on purpose and not validated.' % (
        steps, len (paths), len (commands), len (allErrors), len (allNotes), refusals))
    return 1 if allErrors else 0


if __name__ == '__main__':
    sys.exit (main ())
