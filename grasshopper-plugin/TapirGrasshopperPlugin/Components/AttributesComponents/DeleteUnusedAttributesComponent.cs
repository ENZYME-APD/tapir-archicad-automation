using Grasshopper.Kernel;
using Newtonsoft.Json.Linq;
using System;
using System.Collections.Generic;
using TapirGrasshopperPlugin.Helps;
using TapirGrasshopperPlugin.Types.Attributes;

namespace TapirGrasshopperPlugin.Components.AttributesComponents
{
    public class DeleteUnusedAttributesComponent : ArchicadExecutorComponent
    {
        public override string CommandName => "DeleteUnusedAttributes";

        public DeleteUnusedAttributesComponent()
            : base(
                "DeleteUnusedAttributes",
                "Deletes the unused layers, fills, surfaces, building materials, composites, profiles, line " +
                "types, pen tables and zone categories, for the given types or all of them: exactly the " +
                "attributes GetUnusedAttributes lists. DryRun is true by default, so nothing is deleted unless " +
                "it is set to false. Attributes Archicad does not let you delete are kept and listed with the " +
                "reason. When not every reference could be checked, nothing is deleted. The whole deletion is " +
                "one undo step. Available from Archicad 27.",
                GroupNames.Attributes)
        {
        }

        protected override void AddInputs()
        {
            InTexts(
                "Types",
                GetUnusedAttributesComponent.TypesDescription);

            InBoolean(
                "DryRun",
                "If true, nothing is deleted: the outputs list what would be deleted and what would be kept. " +
                "Set it to false to delete. Default is true.",
                true);

            SetOptionality(new[] { 0, 1 });
        }

        protected override void AddOutputs()
        {
            OutBoolean(
                "DryRun",
                "Whether this was a dry run, in which nothing was deleted.");

            OutTexts(
                "DeletedTypes",
                "The type of each deleted attribute (with DryRun, of each attribute that would be deleted).");

            OutGenerics(
                "DeletedGuids",
                "The identifier of each deleted attribute (with DryRun, that would be deleted).");

            OutIntegers(
                "DeletedIndices",
                "The index of each deleted attribute (with DryRun, that would be deleted).");

            OutTexts(
                "DeletedNames",
                "The name of each deleted attribute (with DryRun, that would be deleted).");

            OutTexts(
                "NotDeletedTypes",
                "The type of each unused attribute that was not deleted (with DryRun, that would not be deleted).");

            OutGenerics(
                "NotDeletedGuids",
                "The identifier of each unused attribute that was not deleted.");

            OutTexts(
                "NotDeletedNames",
                "The name of each unused attribute that was not deleted.");

            OutTexts(
                "NotDeletedReasons",
                "Why each of them was not deleted: Archicad does not let it be deleted, it is generated by a " +
                "library part, Archicad refused to delete it (e.g. it is not reserved in Teamwork), or not every " +
                "reference could be checked.");

            OutTexts(
                "Warnings",
                "What could not be checked; then nothing is deleted.");
        }

        protected override void Solve(
            IGH_DataAccess da)
        {
            var parameters = new JObject
            {
                ["dryRun"] = da.GetOptional(1, true)
            };

            var types = GetUnusedAttributesComponent.ToTypesParameter(da.GetOptionals<string>(0));
            if (types.Count > 0)
            {
                parameters["types"] = types;
            }

            if (!TryGetCadResponse(
                    CommandName,
                    parameters,
                    ToAddOn,
                    out JObject response))
            {
                return;
            }

            var deletedTypes = new List<string>();
            var deletedGuids = new List<AttributeGuidObject>();
            var deletedIndices = new List<object>();
            var deletedNames = new List<string>();
            var notDeletedTypes = new List<string>();
            var notDeletedGuids = new List<AttributeGuidObject>();
            var notDeletedNames = new List<string>();
            var notDeletedReasons = new List<string>();

            foreach (var typeItem in JsonOutputHelp.Items(response, "attributeTypes"))
            {
                var type = typeItem["type"]?.ToString();

                if (typeItem["deletedAttributes"] is JArray deletedAttributes)
                {
                    foreach (var attribute in deletedAttributes)
                    {
                        deletedTypes.Add(type);
                        deletedGuids.Add(attribute["attributeId"]?.ToObject<AttributeGuidObject>());
                        deletedIndices.Add(JsonOutputHelp.Scalar(attribute, "index"));
                        deletedNames.Add(attribute["name"]?.ToString());
                    }
                }

                if (typeItem["notDeletedAttributes"] is JArray notDeletedAttributes)
                {
                    foreach (var attribute in notDeletedAttributes)
                    {
                        notDeletedTypes.Add(type);
                        notDeletedGuids.Add(attribute["attributeId"]?.ToObject<AttributeGuidObject>());
                        notDeletedNames.Add(attribute["name"]?.ToString());
                        notDeletedReasons.Add(attribute["reason"]?.ToString());
                    }
                }
            }

            da.SetData(0, JsonOutputHelp.Scalar(response, "dryRun"));
            da.SetDataList(1, deletedTypes);
            da.SetDataList(2, deletedGuids);
            da.SetDataList(3, deletedIndices);
            da.SetDataList(4, deletedNames);
            da.SetDataList(5, notDeletedTypes);
            da.SetDataList(6, notDeletedGuids);
            da.SetDataList(7, notDeletedNames);
            da.SetDataList(8, notDeletedReasons);
            da.SetDataList(9, GetUnusedAttributesComponent.Warnings(response));
        }

        protected override System.Drawing.Bitmap Icon =>
            Properties.Resources.DeleteAttributes;

        public override Guid ComponentGuid =>
            new Guid("b84f1c62-9e07-4d3b-8a5f-2c6e70d19a4e");
    }
}
